"""Writes a `Report` as an Excel file (M5 spec §7 rule 18, S-41).

Safety: every text cell is written with `write_string`, so a name such as `=HYPERLINK(...)` shows
as text and never runs as a formula. Dates are real dates; minutes are numbers plus an "HH:MM" text
column. The first rows are the header block (company, title, plant, period, generated at and by);
the column header row is frozen. The file is built in memory in the order of the rows.
"""

import io
from datetime import date

import xlsxwriter

from app.core.time import to_ist
from app.modules.reports.model import DATE, INT, MINUTES, Column, Report, Sheet

HEADER_ROWS = 8  # rows of the header block; the column headers are row 9


def hhmm(minutes: int | None) -> str:
    """455 -> "7:35" (hours and minutes; empty for no value)."""
    if minutes is None:
        return ""
    return f"{minutes // 60}:{minutes % 60:02d}"


def build_xlsx(report: Report) -> bytes:
    buffer = io.BytesIO()
    workbook = xlsxwriter.Workbook(buffer, {"in_memory": True, "strings_to_formulas": False})
    formats = {
        "title": workbook.add_format({"bold": True, "font_size": 14}),
        "bold": workbook.add_format({"bold": True}),
        "head": workbook.add_format({"bold": True, "bg_color": "#E8ECF4", "border": 1}),
        "date": workbook.add_format({"num_format": "dd/mm/yyyy"}),
        "total": workbook.add_format({"bold": True, "bg_color": "#F4F6F9"}),
    }
    used_names: set[str] = set()
    for sheet in report.sheets:
        worksheet = workbook.add_worksheet(_unique_name(sheet.name, used_names))
        _header_block(worksheet, report, sheet, formats)
        _table(worksheet, sheet, formats)
    workbook.close()
    return buffer.getvalue()


def _unique_name(name: str, used: set[str]) -> str:
    """Excel tab names: at most 31 characters, none of []:*?/\\, each only once."""
    cleaned = "".join(char for char in name if char not in "[]:*?/\\")[:31] or "Sheet"
    candidate, number = cleaned, 2
    while candidate.lower() in used:
        candidate = f"{cleaned[:28]} {number}"
        number += 1
    used.add(candidate.lower())
    return candidate


def _header_block(worksheet, report: Report, sheet: Sheet, formats: dict) -> None:  # noqa: ANN001
    generated = f"{to_ist(report.generated_at):%d/%m/%Y %H:%M} IST"
    worksheet.write_string(0, 0, "Sheet Shapers – Upasthiti", formats["title"])
    worksheet.write_string(1, 0, report.title, formats["bold"])
    worksheet.write_string(2, 0, f"Plant: {sheet.heading or report.plant_text}")
    worksheet.write_string(3, 0, f"Period: {report.period_text}")
    worksheet.write_string(
        4, 0, f"Generated at: {generated}  ·  Generated by: {report.generated_by}"
    )
    extra = [report.filters] if report.filters else []
    if report.demo_included:
        extra.append("Demo plants included")
    worksheet.write_string(5, 0, "  ·  ".join(extra) if extra else "No filters")
    if report.legend:
        worksheet.write_string(6, 0, "  ·  ".join(report.legend))


def _table(worksheet, sheet: Sheet, formats: dict) -> None:  # noqa: ANN001
    columns = _expanded(sheet.columns)
    for index, (column, _is_hhmm) in enumerate(columns):
        worksheet.write_string(HEADER_ROWS, index, column.header, formats["head"])
        worksheet.set_column(index, index, column.width)
    worksheet.freeze_panes(HEADER_ROWS + 1, 0)
    for row_number, row in enumerate(sheet.rows):
        excel_row = HEADER_ROWS + 1 + row_number
        bold = row_number in sheet.bold_rows
        cell_format = formats["total"] if bold else None
        position = 0
        for column, value in zip(sheet.columns, row, strict=False):
            _write_cell(worksheet, excel_row, position, column, value, cell_format, formats)
            position += 2 if column.kind == MINUTES else 1


def _expanded(columns: list[Column]) -> list[tuple[Column, bool]]:
    """A minutes column becomes two: the number, then the same as HH:MM text."""
    result: list[tuple[Column, bool]] = []
    for column in columns:
        if column.kind == MINUTES:
            result.append((Column(f"{column.header} (min)", INT, column.width), False))
            result.append((Column(f"{column.header} (HH:MM)", "text", column.width), True))
        else:
            result.append((column, False))
    return result


def _write_cell(
    worksheet, row: int, position: int, column: Column, value, cell_format, formats: dict
) -> None:  # noqa: ANN001, E501
    if column.kind == MINUTES:
        if value is None:
            return
        worksheet.write_number(row, position, value, cell_format)
        worksheet.write_string(row, position + 1, hhmm(value), cell_format)
    elif value is None or value == "":
        return
    elif column.kind == DATE and isinstance(value, date):
        worksheet.write_datetime(row, position, value, formats["date"])
    elif column.kind == INT:
        worksheet.write_number(row, position, value, cell_format)
    else:
        # Always a string cell: "=1+1" or "@SUM(A1)" stays text (formula injection).
        worksheet.write_string(row, position, str(value), cell_format)

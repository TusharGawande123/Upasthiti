"""The emergency muster as a PDF (M5 spec §4.2, F-26): one section per plant with a tick box for
the roll call. Same bundled Inter font as the cards and the gate poster (OFL licence)."""

from datetime import datetime
from pathlib import Path

from fpdf import FPDF

from app.core.time import to_ist
from app.modules.dashboard.schemas import MusterResponse

FONT_FOLDER = Path(__file__).resolve().parents[1] / "printing" / "fonts"
FONT_NAME = "Inter"
COLUMNS = (  # (title, width in mm)
    ("", 8),
    ("Code", 20),
    ("Name", 50),
    ("Type", 22),
    ("Department", 32),
    ("Contractor", 36),
    ("IN", 14),
)


class _MusterPdf(FPDF):
    def __init__(self, generated_by: str, generated_at: str) -> None:
        super().__init__(orientation="P", unit="mm", format="A4")
        self.generated_by = generated_by
        self.generated_at = generated_at
        self.add_font(FONT_NAME, "", str(FONT_FOLDER / "Inter-Regular.ttf"))
        self.add_font(FONT_NAME, "B", str(FONT_FOLDER / "Inter-Bold.ttf"))
        self.set_auto_page_break(auto=True, margin=16)
        self.alias_nb_pages()

    def header(self) -> None:
        self.set_font(FONT_NAME, "B", 12)
        self.cell(
            0, 6, "Sheet Shapers – Upasthiti · Emergency muster", new_x="LMARGIN", new_y="NEXT"
        )
        self.set_font(FONT_NAME, "", 8)
        self.cell(
            0,
            4,
            f"List of {self.generated_at} IST · generated by {self.generated_by}",
            new_x="LMARGIN",
            new_y="NEXT",
        )
        self.ln(2)

    def footer(self) -> None:
        self.set_y(-12)
        self.set_font(FONT_NAME, "", 8)
        self.cell(0, 5, f"Page {self.page_no()} of {{nb}}", align="C")


def build_muster_pdf(muster: MusterResponse, generated_by: str) -> bytes:
    moment = to_ist(muster.generated_at)
    pdf = _MusterPdf(generated_by, f"{moment:%d/%m/%Y %H:%M:%S}")
    pdf.add_page()
    for section in muster.plants:
        pdf.set_font(FONT_NAME, "B", 11)
        pdf.cell(
            0,
            7,
            f"{section.plant.code} · {section.plant.name}: {section.count} people inside",
            new_x="LMARGIN",
            new_y="NEXT",
        )
        _header_row(pdf)
        pdf.set_font(FONT_NAME, "", 8)
        for person in section.people:
            employee = person.employee
            _row(
                pdf,
                (
                    "",
                    str(employee["code"]),
                    str(employee["name"]),
                    str(employee["type"]).capitalize(),
                    str(employee["department"] or ""),
                    str(employee["contractor"] or ""),
                    f"{to_ist(person.in_time):%H:%M}",
                ),
            )
        if not section.people:
            pdf.set_font(FONT_NAME, "", 9)
            pdf.cell(0, 6, "Nobody is inside right now.", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)
    return bytes(pdf.output())


def _header_row(pdf: FPDF) -> None:
    pdf.set_font(FONT_NAME, "B", 8)
    for title, width in COLUMNS:
        pdf.cell(width, 6, title, border=1, fill=False)
    pdf.ln()


def _row(pdf: FPDF, values: tuple[str, ...]) -> None:
    for (_title, width), value in zip(COLUMNS, values, strict=True):
        # A tick box in the first column; long text is cut so the row stays one line.
        shown = value if len(value) * 1.6 <= width else value[: max(1, int(width / 1.7))] + "…"
        pdf.cell(width, 6, shown, border=1)
    pdf.ln()


def muster_file_name(plant_code: str | None, moment: datetime) -> str:
    return f"upasthiti-muster-{plant_code or 'ALL'}-{to_ist(moment):%Y%m%d-%H%M}.pdf"

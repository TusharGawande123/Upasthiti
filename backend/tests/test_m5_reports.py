def cells(content: bytes) -> list[list[str]]:
    """Every cell of every sheet as text, row by row."""
    workbook = openpyxl.load_workbook(io.BytesIO(content))
    return [
        [str(cell) for cell in row if cell is not None]
        for sheet in workbook.worksheets
        for row in sheet.iter_rows(values_only=True)
    ]


def flat(content: bytes) -> str:
    return "\n".join(" | ".join(row) for row in cells(content))


def pdf_text(content: bytes) -> str:
    document = pdfium.PdfDocument(content)
    return "\n".join(page.get_textpage().get_text_range() for page in document)



def test_limits_and_validation(world: dict) -> None:
    boss = world["boss"]
    unknown = boss.get("/api/v1/reports/nothing.xlsx", params={"date": FRIDAY.isoformat()})
    assert unknown.status_code == 404
    assert unknown.json()["error"]["code"] == "REPORT_KIND_UNKNOWN"
    too_long = boss.get(
        "/api/v1/reports/exceptions.xlsx",
        params={"date_from": "2026-09-01", "date_to": FRIDAY.isoformat()},
    )
    assert too_long.json()["error"]["code"] == "REPORT_RANGE_TOO_LONG"
    future = boss.get("/api/v1/reports/daily-muster.xlsx", params={"date": "2026-11-05"})
    assert future.status_code == 422


def test_twenty_files_in_ten_minutes_then_refused(world: dict) -> None:
    params = {"date": FRIDAY.isoformat(), "plant_id": world["plant"].id}

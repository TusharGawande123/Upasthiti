def test_a_name_that_looks_like_a_formula_stays_text(world: dict) -> None:
    """S-41: =HYPERLINK(...) is written as a string cell, never as a formula."""
    response = world["boss"].get(
        "/api/v1/reports/daily-muster.xlsx",
        params={"date": FRIDAY.isoformat(), "plant_id": world["plant"].id},
    )
    workbook = openpyxl.load_workbook(io.BytesIO(response.content))
    found = [
        cell
        for sheet in workbook.worksheets
        for row in sheet.iter_rows()
        for cell in row
        if cell.value == FORMULA_NAME
    ]
    assert found
    assert all(cell.data_type == "s" for cell in found)


